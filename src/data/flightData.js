// Helper: resolve airport from code or city name
export function findAirport(searchTerm) {
  if (!searchTerm) return null;
  const term = searchTerm.toLowerCase().trim();
  return AIRPORTS.find(
    (a) => a.code.toLowerCase() === term || a.city.toLowerCase() === term
  ) || null;
}

