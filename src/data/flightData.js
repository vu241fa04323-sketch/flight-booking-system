// Main flight search function
export function searchFlights({ from, to, departureDate, travelClass = 'economy' }) {
  const fromAp = findAirport(from);
  const toAp = findAirport(to);

  if (!fromAp || !toAp) {
    return [];
  }

  // Look for curated matches first
  const curated = INITIAL_FLIGHTS.filter(
    (f) => f.fromCode === fromAp.code && f.toCode === toAp.code
  );

  if (curated.length > 0) {
    return curated;
  }

  // Fallback: generate high-quality dynamic realistic flights for the pair
  return generateDynamicFlights(fromAp, toAp, departureDate, travelClass);
}
